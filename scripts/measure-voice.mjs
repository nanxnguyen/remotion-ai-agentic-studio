// Measure every voice.json clip with ffprobe and write a typed VOICE_SECONDS module, so
// timelines come from real clip lengths instead of hand-written PROPOSED_FRAMES.
// Usage: node scripts/measure-voice.mjs <vid> [--audio <folder>] [--out <file.ts>]
// No shebang on purpose: a CRLF checkout turns "#!...\r" into a vitest parse error.
import {spawnSync} from 'node:child_process';
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const OPTIONS = new Set(['--audio', '--out']);

export function parseMeasureArgs(argv) {
  const [vid, ...rest] = argv;
  if (!vid || !SLUG.test(vid)) throw new Error('First argument must be a kebab-case video id');
  const result = {vid, audio: undefined, out: undefined};
  for (let i = 0; i < rest.length; i += 2) {
    const arg = rest[i];
    if (!OPTIONS.has(arg)) throw new Error(`Unknown option: ${arg}`);
    const value = rest[i + 1];
    if (!value || value.startsWith('--')) throw new Error(`Missing value for ${arg}`);
    result[arg.slice(2)] = value;
  }
  return result;
}

const audioFolder = (root, vid, audio) => {
  if (audio) return audio;
  const status = path.join(root, 'docs', vid, 'status.json');
  if (!existsSync(status)) return vid;
  return JSON.parse(readFileSync(status, 'utf8')).paths?.audio ?? vid;
};

const probeSeconds = (file) => {
  const probe = spawnSync(
    'ffprobe',
    ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file],
    {encoding: 'utf8'},
  );
  const seconds = Number.parseFloat(probe.stdout);
  if (probe.status !== 0 || !Number.isFinite(seconds) || seconds <= 0) {
    throw new Error(`ffprobe could not read ${file}: ${probe.stderr || probe.stdout}`.trim());
  }
  // Round up to the millisecond: the timeline rounds up again to frames, never down.
  return Math.ceil(seconds * 1000) / 1000;
};

export function measureVoice({root = process.cwd(), vid, audio}) {
  const voiceJson = path.join(root, 'docs', vid, 'voice.json');
  if (!existsSync(voiceJson)) throw new Error(`Missing ${path.relative(root, voiceJson)}`);
  const keys = Object.keys(JSON.parse(readFileSync(voiceJson, 'utf8')));
  if (keys.length === 0) throw new Error('voice.json has no keys');
  const dir = path.join(root, 'public', 'audio', audioFolder(root, vid, audio));
  const missing = keys.filter((key) => !existsSync(path.join(dir, `${key}.mp3`)));
  if (missing.length) {
    const rel = path.relative(root, dir).replaceAll('\\', '/');
    throw new Error(`Missing clips in ${rel}/: ${missing.map((key) => `${key}.mp3`).join(', ')}`);
  }
  return Object.fromEntries(keys.map((key) => [key, probeSeconds(path.join(dir, `${key}.mp3`))]));
}

export function renderDurationsModule(seconds, audio) {
  const rows = Object.entries(seconds).map(([key, value]) => {
    const name = /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
    return `  ${name}: ${value},`;
  });
  return [
    `// Generated by scripts/measure-voice.mjs from public/audio/${audio}/ -- do not edit by hand.`,
    '// Re-run it after any clip is regenerated, then rebuild the timeline from these values.',
    'export const VOICE_SECONDS = {',
    ...rows,
    '} as const;',
    '',
  ].join('\n');
}

export function main(argv = process.argv.slice(2), root = process.cwd()) {
  try {
    const options = parseMeasureArgs(argv);
    const audio = audioFolder(root, options.vid, options.audio);
    const seconds = measureVoice({root, vid: options.vid, audio});
    const source = renderDurationsModule(seconds, audio);
    if (options.out) {
      writeFileSync(path.resolve(root, options.out), source);
      console.log(`wrote ${options.out} (${Object.keys(seconds).length} clips)`);
    } else {
      process.stdout.write(source);
    }
    return 0;
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    return 1;
  }
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))
) {
  process.exitCode = main();
}
